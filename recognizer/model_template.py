"""Judge whether a Terra Mystica map looks like it was made by the smart map generator.

    python map_is_smart.py map.txt            -> prints a score between 0 and 1
    python map_is_smart.py map.txt --verbose  -> also prints the rule checks

The map file has one line per map row, hexes separated by commas, as written by the map generator and as uploaded
to Board Game Arena:  R red, Y yellow, U brown, K black, B blue, G green, S gray, I river.
The snellman format (rows separated by ';', a leading ';' for a short first row) is accepted as well.
Rows must alternate between n and n+1 hexes (either one first), or all have n hexes. In the latter case the 2nd,
4th, ... rows are taken to be indented by half a hex (--indent-first: the 1st, 3rd, ...).

The score is only a probability for maps that come from one of the two generators the model was trained on
(with equal odds). For other maps it says which generator the map resembles more.
Only numpy is needed. This file is generated by train.py (recognizer/export.py); the weights are embedded below.
"""
import argparse
import json
import sys

import numpy as np

LETTERS = {'R': 0, 'Y': 1, 'U': 2, 'K': 3, 'B': 4, 'G': 5, 'S': 6, 'I': 7}
RIVER = 7
WEIGHTS = None  # filled in by recognizer/export.py


# ---------------------------------------------------------------- reading a map

def parse_map(text, indent_first=False):
    """Map text -> (rows, indented): rows = list of lists of terrain codes, indented[r] = row r is shifted
    right by half a hex."""
    rows = []
    for line in text.replace(';', '\n').splitlines():
        tokens = [t for t in line.replace(',', ' ').split() if t]
        if not tokens:
            continue
        try:
            rows.append([LETTERS[t.upper()] for t in tokens])
        except KeyError as e:
            raise ValueError(f'unknown terrain letter {e} (allowed: {", ".join(LETTERS)})')
    if not rows:
        raise ValueError('the map is empty')
    lengths = [len(r) for r in rows]
    if len(set(lengths)) == 1:
        indented = [(r % 2 == 0) if indent_first else (r % 2 == 1) for r in range(len(rows))]
    elif len(set(lengths)) == 2 and max(lengths) - min(lengths) == 1 and \
            all(lengths[r] != lengths[r + 1] for r in range(len(rows) - 1)):
        indented = [n == min(lengths) for n in lengths]
    else:
        raise ValueError(f'row lengths {lengths}: rows must alternate between n and n+1 hexes or all have n hexes')
    return rows, indented


def neighbour(rows, indented, r, c, d):
    """Hex in direction d (0 down-right, 1 right, 2 up-right, 3 up-left, 4 left, 5 down-left) or None."""
    s = 1 if indented[r] else 0
    rr, cc = {0: (r + 1, c + s), 1: (r, c + 1), 2: (r - 1, c + s),
              3: (r - 1, c + s - 1), 4: (r, c - 1), 5: (r + 1, c + s - 1)}[d]
    if 0 <= rr < len(rows) and 0 <= cc < len(rows[rr]):
        return rr, cc
    return None


def hex_graph(rows, indented):
    """Nodes = all hexes (land and river) in reading order; returns (cells, adjacency matrix)."""
    cells = [(r, c) for r in range(len(rows)) for c in range(len(rows[r]))]
    index = {cell: i for i, cell in enumerate(cells)}
    adj = np.zeros((len(cells), len(cells)), dtype=np.float32)
    for (r, c), i in index.items():
        for d in range(6):
            n = neighbour(rows, indented, r, c, d)
            if n is not None:
                adj[i, index[n]] = 1.0
    return cells, adj


def features(rows, cells):
    """One-hot vectors: 7 colours + river."""
    x = np.zeros((len(cells), 8), dtype=np.float32)
    for i, (r, c) in enumerate(cells):
        x[i, rows[r][c]] = 1.0
    return x


# ---------------------------------------------------------------- rule checks (as in the smart generator)

def same_colour_pairs(rows, indented):
    pairs = 0
    for r in range(len(rows)):
        for c in range(len(rows[r])):
            for d in (0, 1, 5):  # each pair once
                n = neighbour(rows, indented, r, c, d)
                if n is not None and rows[r][c] != RIVER and rows[n[0]][n[1]] == rows[r][c]:
                    pairs += 1
    return pairs


def number_test(rows):
    """Smart generator's number_test: all colours (almost) equally frequent."""
    land = [v for row in rows for v in row if v != RIVER]
    n = len(land)
    deltas = [abs(land.count(c) - n / 7) for c in range(7)]
    return sum(deltas) <= 3 if n % 7 == 0 else all(d <= 1 for d in deltas)


def river_access(rows, indented, r, c):
    is_river = lambda h: h is not None and rows[h[0]][h[1]] == RIVER
    nb = [neighbour(rows, indented, r, c, d) for d in range(6)]
    adjacent = False
    for d in range(6):
        if is_river(nb[d]):
            if is_river(nb[(d + 3) % 6]):
                return 2
            if is_river(nb[(d + 2) % 6]) and not is_river(nb[(d + 1) % 6]):
                return 2
            if is_river(nb[(d - 2) % 6]) and not is_river(nb[(d - 1) % 6]):
                return 2
            adjacent = True
    return 1 if adjacent else 0


def river_access_test(rows, indented):
    """Smart generator's river_access_test: no colour has much better river access than the average."""
    score = [0] * 7
    for r in range(len(rows)):
        for c in range(len(rows[r])):
            if rows[r][c] != RIVER:
                score[rows[r][c]] += river_access(rows, indented, r, c)
    average = sum(score) / 7
    return all(s - average <= 2 for s in score)


# ---------------------------------------------------------------- the network (numpy)

def score(rows, indented, weights=None):
    w = weights or WEIGHTS
    cells, adj = hex_graph(rows, indented)
    h = features(rows, cells)
    for layer in w['graph']:
        h = np.maximum(0, h @ np.array(layer['self_w']).T + np.array(layer['self_b'])
                       + (adj @ h) @ np.array(layer['nb_w']).T)
    v = np.concatenate([h.mean(axis=0), h.max(axis=0)])
    for layer in w['dense']:
        v = np.maximum(0, np.array(layer['w']) @ v + np.array(layer['b']))
    z = float(np.array(w['out']['w']) @ v + w['out']['b'][0])
    return 1 / (1 + np.exp(-z))


def main():
    p = argparse.ArgumentParser(description='Score between 0 and 1: does the map look like it was made by the smart generator?')
    p.add_argument('map', help='map file (one row per line, e.g. "U,S,G,B,..."; or snellman format)')
    p.add_argument('--indent-first', action='store_true', help='maps with equal row lengths: the 1st row is indented')
    p.add_argument('--verbose', action='store_true', help='print the rule checks and the model description')
    args = p.parse_args()

    try:
        with open(args.map, encoding='utf-8') as f:
            rows, indented = parse_map(f.read(), args.indent_first)
    except (OSError, ValueError) as e:
        sys.exit(f'error: {e}')

    checks = {
        'no adjacent hexes of the same colour': same_colour_pairs(rows, indented) == 0,
        'number_test': number_test(rows),
        'river_access_test': river_access_test(rows, indented),
    }
    print(f'{score(rows, indented):.3f}')
    for name, ok in checks.items():
        if args.verbose or not ok:
            print(f'{"ok" if ok else "WARNING, failed"}: {name}', file=sys.stderr)
    if args.verbose:
        print(f'model: {WEIGHTS.get("info", "")}', file=sys.stderr)


if __name__ == '__main__':
    main()
